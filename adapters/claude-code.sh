#!/bin/sh
# Claude Code adapter: project the neutral core onto Claude Code's memory files.
#   always-on/* -> ./CLAUDE.md (concatenated, committed to repo root or ~/.claude/CLAUDE.md)
#   projects/*  -> ./.claude/context/<name>.md (referenced on demand)
#
# Usage:
#   ./adapters/claude-code.sh apply [target-dir]
#   ./adapters/claude-code.sh wire
#   ./adapters/claude-code.sh measure [target-dir] [--baseline-tokens N]
#
# wire: live parity with a Model install (run after ccb-bootstrap.sh). Instead of copying the core,
#   Claude Code reads the SAME files Model reads, so edits apply to both agents at once:
#   - ~/.claude/CLAUDE.md gets a marked block that @imports every ~/.kiro/steering/*.md
#   - ~/.claude/settings.json SessionStart runs the same hook files as Model's agentSpawn
#     (the Model-only steering-loader-guard excluded); other settings are preserved
#   - ~/.claude/skills/<frontmatter name> links to each ~/.kiro/skills/<dir> (same skill names)
#   - repo steering: ccb-project-context.sh keeps each active repo's CLAUDE.local.md importing its
#     .kiro/steering (what Model auto-loads as workspace steering), git-excluded, never committed
#   Then runs ccb-parity-check.sh. Idempotent.
#
# measure: token-accurate breakdown of what CCB adds to Claude Code.
#   Without --baseline-tokens: reports CCB-marginal savings only.
#   With --baseline-tokens N:  also reports total-context savings (CCB + fixed agent overhead).
#   Note: Claude Code has no disableInheritingDefaultResources equivalent, so the system
#   prompt is always loaded on top of CLAUDE.md. Pass --baseline-tokens to account for it
#   and get honest numbers comparable to a Model run with the override on.
set -eu

CORE="${CCB_HOME:-${HOME}/.context-config-builder}"
SCRIPT_DIR="$(cd "$(dirname "$0")/.." && pwd)"
CMD="${1:-}"

case "$CMD" in
  apply)
    DEST="${2:-$PWD}"
    [ -d "$CORE" ] || { echo "error: core not found at $CORE" >&2; exit 1; }
    mkdir -p "$DEST/.claude/context"
    {
      echo "# Project Memory (always-on)  -  generated by context-config-builder"
      echo
      for f in "$CORE"/always-on/*.md; do
        [ -e "$f" ] || continue
        echo "<!-- $(basename "$f") -->"; cat "$f"; echo
      done
      echo "## On-demand context"
      echo "When a task touches a project, read the matching file in .claude/context/<name>.md."
    } > "$DEST/CLAUDE.md"
    for f in "$CORE"/projects/*.md; do
      [ -e "$f" ] || continue
      cp "$f" "$DEST/.claude/context/$(basename "$f")"
    done
    echo "Claude Code adapter: wrote $DEST/CLAUDE.md and $DEST/.claude/context/*"
    ;;

  wire)
    KH="${KIRO_HOME:-$HOME/.kiro}"; CH="${CLAUDE_HOME:-$HOME/.claude}"
    [ -d "$KH/steering" ] || { echo "error: $KH/steering not found; run ccb-bootstrap.sh first" >&2; exit 1; }
    mkdir -p "$CH/skills"
    KH="$KH" CH="$CH" python3 - <<'PY'
import json, os, re
KH, CH = os.environ["KH"], os.environ["CH"]
# 1. CLAUDE.md: marked, regenerated block of @imports (content outside the markers is preserved)
B, E = "<!-- ccb:steering begin (adapters/claude-code.sh wire) -->", "<!-- ccb:steering end -->"
files = sorted(f for f in os.listdir(f"{KH}/steering") if f.endswith(".md"))
block = "\n".join([B, "# CCB always-on steering (live imports; same files Model loads)"] + [f"@~/.kiro/steering/{f}" for f in files] + [E])
p = f"{CH}/CLAUDE.md"
cur = open(p).read() if os.path.exists(p) else ""
new = re.sub(re.escape(B) + r".*?" + re.escape(E), lambda m: block, cur, flags=re.S) if B in cur else (block + "\n\n" + cur).rstrip() + "\n"
if new != cur: open(p, "w").write(new)
print(f"  CLAUDE.md: {len(files)} steering imports")
# 2. settings.json SessionStart mirrors Model agentSpawn (guard excluded)
def load(q):
    try: return json.load(open(q))
    except Exception: return {}
spawn = load(f"{KH}/agents/default.json").get("hooks", {}).get("agentSpawn", [])
cmds = [h["command"].replace("~/", "$HOME/", 1) for h in spawn if isinstance(h, dict) and h.get("command") and not h["command"].endswith("steering-loader-guard.sh")]
sp = f"{CH}/settings.json"; st = load(sp)
st.setdefault("hooks", {})["SessionStart"] = [{"hooks": [{"type": "command", "command": c, "timeout": 20} for c in cmds]}]
json.dump(st, open(sp, "w"), indent=2); open(sp, "a").write("\n")
print(f"  settings.json: SessionStart mirrors {len(cmds)} Model agentSpawn hook(s)")
# 3. skills under their frontmatter name
n = 0
for d in sorted(os.listdir(f"{KH}/skills")) if os.path.isdir(f"{KH}/skills") else []:
    sk = f"{KH}/skills/{d}/SKILL.md"
    if not os.path.isfile(sk): continue
    m = re.search(r"^name:\s*(\S+)", open(sk).read(), re.M); name = m.group(1) if m else d
    dst = f"{CH}/skills/{name}"
    if os.path.islink(dst) and os.path.realpath(dst) != os.path.realpath(f"{KH}/skills/{d}"): os.remove(dst)
    if not os.path.exists(dst): os.symlink(f"{KH}/skills/{d}", dst)
    n += 1
print(f"  skills: {n} linked under frontmatter names")
PY
    # repo steering (CLAUDE.local.md) is maintained by the shared hook; run it once now
    [ -x "$KH/hooks/ccb-project-context.sh" ] && sh "$KH/hooks/ccb-project-context.sh" >/dev/null 2>&1
    echo "Claude Code adapter: wired to $KH (live, no copies)"
    [ -x "$KH/hooks/ccb-parity-check.sh" ] && KIRO_HOME="$KH" CLAUDE_HOME="$CH" sh "$KH/hooks/ccb-parity-check.sh"
    ;;

  measure)
    # Parse remaining args: optional target-dir and --baseline-tokens N
    DEPLOY="${HOME}/.claude"; BASELINE=0
    shift
    while [ $# -gt 0 ]; do
      case "$1" in
        --baseline-tokens) BASELINE="$2"; shift 2 ;;
        *) DEPLOY="$1"; shift ;;
      esac
    done

    BM="$SCRIPT_DIR/benchmark/benchmark.py"
    [ -f "$BM" ] || { echo "error: benchmark.py not found at $BM" >&2; exit 1; }

    # Claude Code layout: CLAUDE.md (always-on) + .claude/context/*.md (on-demand, no frontmatter)
    # Remap into the steering/skills structure benchmark.py expects.
    TMP=$(mktemp -d)
    trap 'rm -rf "$TMP"' EXIT
    mkdir -p "$TMP/steering" "$TMP/skills"

    [ -f "$DEPLOY/CLAUDE.md" ] && cp "$DEPLOY/CLAUDE.md" "$TMP/steering/CLAUDE.md"

    # Each context file becomes a skill dir. No frontmatter -> meta_tokens returns 0
    # (correct: Claude Code on-demand files load fully or not at all, no partial metadata).
    for f in "$DEPLOY/context"/*.md; do
      [ -e "$f" ] || continue
      name="$(basename "$f" .md)"
      mkdir -p "$TMP/skills/$name"
      cp "$f" "$TMP/skills/$name/SKILL.md"
    done

    if [ "$BASELINE" -eq 0 ] 2>/dev/null; then
      echo "WARNING: --baseline-tokens not set. Reporting CCB-marginal savings only." >&2
      echo "         Claude Code always loads a system prompt on top of CLAUDE.md." >&2
      echo "         Pass --baseline-tokens N for honest total-context numbers." >&2
    fi

    python3 "$BM" --context-root "$TMP" --agent-baseline "$BASELINE"
    ;;

  *)
    echo "usage: claude-code.sh apply [target-dir]" >&2
    echo "       claude-code.sh wire" >&2
    echo "       claude-code.sh measure [target-dir] [--baseline-tokens N]" >&2
    exit 2
    ;;
esac
